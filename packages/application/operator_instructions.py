"""Repo-owned, read-only knowledge-base content for the operator portal.

The module deliberately has no runtime persistence or browser editing path.  The
HTTP adapter renders this structured content only after its route capability
check has completed.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class InstructionBlock:
    """One safe, renderer-owned semantic block in an operator instruction."""

    kind: str
    title: str = ""
    text: str = ""
    items: tuple[str, ...] = ()
    rows: tuple[tuple[str, ...], ...] = ()
    headers: tuple[str, ...] = ()


@dataclass(frozen=True)
class InstructionSection:
    anchor: str
    title: str
    lead: str = ""
    blocks: tuple[InstructionBlock, ...] = ()


@dataclass(frozen=True)
class OperatorInstruction:
    instruction_id: str
    title: str
    summary: str
    sections: tuple[InstructionSection, ...]


